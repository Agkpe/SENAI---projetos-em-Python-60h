# operadores aritméticos
# (+  -   *    /   //   %   ** ) = a  saída é um número

# básicos
print(10+2)
print(10-2)
print(10*2)
print(10/2)
# potencia
print(10**2)

#Raiz quadrada
raiz = 16**(0.5)
print('raiz quadrada', raiz)

# div c/ 2 barras
print(10//2) #sai somente número inteiro

# módulo -  resto da conta de divisão
print(10%2)


# operadores lógicos  -  saída é um dado lógico
# True ou False

print(10 > 2)
print(10 < 2)
print(10 >= 2)
print(10 <= 2)
print(10 == 2)
print(10 != 2)

# Python segue o PEMDAS -> Ordem de prioridade de cada equação
